import yaml
import importlib
from pathlib import Path
import inspect

def generate_interface(config_path: str, output_path: str="main.py"):
    with open(config_path, "r") as f:
        config = yaml.safe_load(f)

    observations=config.get("observations", [])
    actions=config.get("actions", [])

    sensor_types = [obs["type"] for obs in observations]
    action_types = [act["type"] for act in actions]

    sensor_classes = [obs["class"] for obs in observations]
    action_classes = [act["class"] for act in actions]

    imports = set()
    for cls,type in zip(sensor_classes, sensor_types):
        imports.add(f"from {type} import {cls}")

    for cls,type in zip(action_classes, action_types):
        imports.add(f"from {type} import {cls}")

    imports = "\n".join(imports)

    observe_lines = []
    for i in range(len(observations)):
        obs = observations[i]
        observe_line=''
        observe_line+=f"obs{i} = {obs['class']}("
        for key, value in obs.items():
            if key not in ["name", "type", "class","scale","offset"]:
                observe_line+=f"{key}='{value}',"
        observe_lines.append(observe_line+")")
    observe_lines = "\n".join(observe_lines)

    action_lines = []
    for i in range(len(actions)):
        act = actions[i]
        act_line = ''
        act_line += f"act{i} = {act['class']}("
        for key, value in act.items():
            if key not in ["name", "type", "class", "min", "max"]:
                act_line += f"{key}={value},"
        action_lines.append(act_line+")")
    action_lines = "\n".join(action_lines)

    lines=[]

    lines.append("# Auto-generated by simtoreal")
    lines.append("")
    lines.append("from policy_network import policy_forward")
    lines.append(imports)
    lines.append("")
    lines.append("#observations")
    lines.append(observe_lines)
    lines.append("")
    lines.append("#actions")
    lines.append(action_lines)
    lines.append("")
    lines.append("def observe():")
    lines.append("    return [")
    for i in range(len(observations)):
        lines.append(f"        obs{i}.read(),")
    lines.append("    ]")
    lines.append("")
    lines.append("def apply_actions(actions):")
    for i in range(len(actions)):
        lines.append(f"    act{i}.write(actions[{i}])")
    lines.append("")
    lines.append("def policy():")
    lines.append("    obs = observe()")
    lines.append("    actions = policy_forward(obs)")
    lines.append("    apply_actions(actions)")
    lines.append("")
    lines.append("if __name__ == '__main__':")
    lines.append("    while True:")
    lines.append("        policy()")
    lines.append("")

    Path(output_path).write_text("\n".join(lines))
    print(f"Generated : {output_path}")


if __name__ == "__main__":
    generate_interface(config_path="config.yaml", output_path="main.py")